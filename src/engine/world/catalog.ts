/**
 * Средняя суточная температура воздуха, °C. Опорные дни сезона — из
 * библии: 02.12 −34, 06.12 −41, остальное — плавно и детерминированно.
 */
export function outdoorTemp(ms: number): number {
  const day = startOfDay(ms);
  const anchors: [number, number][] = [
    [parseTs("2026-09-01"), 6],
    [parseTs("2026-10-01"), -2],
    [parseTs("2026-11-01"), -14],
    [parseTs("2026-11-15"), -22],
    [parseTs("2026-11-18"), -27],
    [parseTs("2026-12-01"), -31],
    [parseTs("2026-12-02"), -34],
    [parseTs("2026-12-05"), -38],
    [parseTs("2026-12-06"), -41],
    [parseTs("2026-12-08"), -33],
    [parseTs("2026-12-15"), -36],
    [parseTs("2026-12-21"), -38],
    [parseTs("2026-12-31"), -30],
    [parseTs("2027-01-11"), -38],
  ];
  if (day <= anchors[0][0]) return anchors[0][1];
  for (let i = 1; i < anchors.length; i++) {
    const [t1, v1] = anchors[i];
    const [t0, v0] = anchors[i - 1];
    if (day <= t1) {
      const f = (day - t0) / (t1 - t0);
      // Небольшая детерминированная «погода» поверх тренда
      const wobble = Math.sin(day / DAY / 2.3) * 2.2;
      return Math.round((v0 + (v1 - v0) * f + (i > 4 ? wobble : 0)) * 10) / 10;
    }
  }
  return anchors[anchors.length - 1][1];
}

/** Сколько машин на улицах в мороз: −25 и теплее — 1, −41 — ~0,55 */
export function frostFactor(ms: number): number {
  const t = outdoorTemp(ms);
  return t >= -25 ? 1 : Math.max(0.45, 1 - (-25 - t) * 0.028);
}

/** Дорожный ритм: пики 7–9 и 17–19, ночью почти пусто, выходные слабее */
export function trafficWeight(ms: number): number {
  const h = hourOfDay(ms);
  let w: number;
  if (h < 5) w = 0.04;
  else if (h < 6.5) w = 0.12;
  else if (h < 7) w = 0.4;
  else if (h < 9) w = 1;
  else if (h < 12) w = 0.45;
  else if (h < 14) w = 0.55;
  else if (h < 17) w = 0.45;
  else if (h < 19) w = 0.95;
  else if (h < 22) w = 0.35;
  else w = 0.12;
  if (isWeekend(ms)) w *= h >= 7 && h < 9 ? 0.35 : 0.7;
  return w * frostFactor(ms);
}

/** Ритм вызовов полиции: вечер и ночь выходных — пик, утро — заявления */
export function incidentWeight(ms: number): number {
  const h = hourOfDay(ms);
  let w: number;
  if (h < 3) w = 0.55;
  else if (h < 7) w = 0.2;
  else if (h < 10) w = 0.65;
  else if (h < 16) w = 0.6;
  else if (h < 23) w = 1;
  else w = 0.8;
  if (isWeekend(ms) && (h >= 20 || h < 4)) w = Math.min(1, w * 1.3);
  return w;
}

/** Рабочий день учреждения: 8–19 будни, слабо — вечер, почти ноль ночью и в выходные */
export function officeWeight(ms: number): number {
  const h = hourOfDay(ms);
  let w: number;
  if (h < 7) w = 0.01;
  else if (h < 8.5) w = 0.3;
  else if (h < 13) w = 1;
  else if (h < 14) w = 0.5;
  else if (h < 18.5) w = 0.95;
  else if (h < 21) w = 0.2;
  else w = 0.03;
  return isWeekend(ms) ? w * 0.08 : w;
}

/** Покупки: обед и вечер */
export function shoppingWeight(ms: number): number {
  const h = hourOfDay(ms);
  if (h < 7) return 0.02;
  if (h < 11) return 0.3;
  if (h < 12) return 0.5;
  if (h < 14.5) return 1;
  if (h < 17) return 0.45;
  if (h < 20.5) return 0.95;
  if (h < 23) return 0.35;
  return 0.05;
}

/** Переписка: день и вечер, ночью редко */
export function messagingWeight(ms: number): number {
  const h = hourOfDay(ms);
  if (h < 1) return 0.2;
  if (h < 7) return 0.04;
  if (h < 9) return 0.5;
  if (h < 18) return 0.75;
  if (h < 23) return 1;
  return 0.4;
}

/** Домофоны: утренний выход и вечернее возвращение */
export function doorbellWeight(ms: number): number {
  const h = hourOfDay(ms);
  if (h < 6) return 0.03;
  if (h < 9) return 0.8;
  if (h < 16) return 0.35;
  if (h < 22) return 1;
  return 0.15;
}

/**
 * Дата создания карточки в ПБД по id: «Сокол» с 2015-03-01, ПБД с 2017-го,
 * id растут со временем, последняя шумовая — до вечера 18.11.2026. Используют
 * и посадки, и шум — у каста те же правила.
 */
export function personCreatedAt(id: number): number {
  const t0 = parseTs("2015-03-01 09:00:00");
  // До вечера 18.11: после смерти Ирины в ПБД завели одну карточку — «мёртвую душу» 4301
  const t1 = parseTs("2026-11-18 18:00:00");
  const f = Math.min(1, Math.max(0, (id - 1) / 4300));
  const jitter = (((id * 2654435761) >>> 0) % 7200) * 60_000; // до 5 суток, детерминированно
  const base = t0 + f * (t1 - t0 - 5 * DAY);
  return officeMoment(base + jitter, id);
}

/**
 * Тот же день (или ближайший будний до него), но в рабочее время 08:30–18:30
 * с детерминированными минутами и секундами: карточки ПДн заводят днём. Ночная
 * карточка — примета подделки (Кравец, 2026-11-20 02:22:00).
 */
export function officeMoment(ms: number, salt: number): number {
  let day = startOfDay(ms);
  while (isWeekend(day)) day -= DAY;
  const minute = 8 * 60 + 30 + (((salt * 40503 + 7) >>> 0) % 600);
  const second = ((salt * 2246822519) >>> 0) % 60;
  return day + minute * 60_000 + second * 1000;
}

