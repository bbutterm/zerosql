export function plant(ctx: WorldContext): void {
  // --- ночь 10.01: «Бастион» у ГУ на камере 2 «Площадь Труда»
  for (const [at, direction, confidence] of [
    [C12_NIGHT.plateIn, "въезд", 0.97],
    [C12_NIGHT.plateOut, "выезд", 0.95],
  ] as const) {
    ctx.insert("plate_reads", { camera_id: F.CAMERA.trudaSquare, plate: F.PLATE.bastion, read_at: at, confidence, direction }, { orderAt: ts(at) });
  }

  // --- аварийное открытие серверной без пропуска
  ctx.insert("door_access", {
    ts: C12_NIGHT.serverDoor, badge_id: null, door: "Серверная", direction: "вход", note: C12_SERVER_DOOR_NOTE,
  }, { orderAt: ts(C12_NIGHT.serverDoor) });

  // --- вход по админ-токену Лыкова: сеанс a.lykov переключён на nol
  ctx.insert("audit_log", {
    ts: C12_NIGHT.session, login: F.LOGIN.lykov, workstation: F.WORKSTATION.serverRoom, action: "SESSION",
    table_name: "logins", row_id: F.LOGIN.player, field: "user", old_value: F.LOGIN.lykov, new_value: F.LOGIN.player,
  }, { orderAt: ts(C12_NIGHT.session) });

  // --- выгрузка журнала игрока: ту распечатку Гранин положит на стол (М24)
  ctx.insert("query_log", {
    logged_at: C12_NIGHT.logExport, login: F.LOGIN.player, terminal: F.WORKSTATION.serverRoom, query_text: C12_EXPORT_SQL,
    rows_returned: null, status: "ok", ts_real: null, case_id: null, objective_id: null, run_id: null,
  }, { orderAt: ts(C12_NIGHT.logExport) });

  // --- 11.01: живая лента Бурцева по гостевому пропуску
  ctx.reserve("badge", C12_GUEST_BADGE, F.PERSON.burtsev);
  for (const [i, row] of C12_FEED.entries()) {
    ctx.insert("door_access", {
      ts: row.ts, badge_id: C12_GUEST_BADGE, door: row.door, direction: "вход", note: i === 0 ? C12_GUEST_NOTE : null,
    }, { orderAt: ts(row.ts) });
  }

  // --- шум не создаёт второго ответа
  const nightFrom = "2027-01-10 00:00:00";
  const nightTo = "2027-01-10 06:00:00";
  ctx.exclude("door_access", (r) => r.door === "Серверная" && String(r.ts) >= nightFrom && String(r.ts) < nightTo,
    "серверная в ночь на 10.01 — только аварийное открытие");
  ctx.exclude("door_access", (r) => r.badge_id === null || /аварийн/i.test(String(r.note ?? "")),
    "проход без пропуска — только аварийное открытие 10.01");
  ctx.exclude("door_access", (r) => String(r.ts) >= "2027-01-11 00:00:00", "11.01 — только лента Бурцева");
  ctx.exclude("door_access", (r) => /^Лестница|тамбур/i.test(String(r.door ?? "")), "лестницы и тамбур — только лента");
  ctx.exclude("audit_log", (r) => r.action === "SESSION" && String(r.ts) >= nightFrom, "сеансы 10.01 — только вход по токену");
  ctx.exclude("plate_reads", (r) => r.camera_id === F.CAMERA.trudaSquare && String(r.read_at) >= nightFrom && String(r.read_at) < nightTo,
    "камера 2 в ночь на 10.01 — только «Бастион»");
}

