function birthDate(db: Database, personId: number): string | null {
  if (personId === P.dasha) return DASHA_BIRTH;
  const r = db.exec("SELECT birth_date FROM main.persons WHERE id = ?", [personId]);
  const v = r[0]?.values[0]?.[0];
  return typeof v === "string" ? v : null;
}

