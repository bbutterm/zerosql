const INVARIANT = /(?:ко|ия|ой|им|их|ых)$/;

export function feminineSurname(male: string): string {
  if (/(?:ский|цкий)$/.test(male)) return male.replace(/ий$/, "ая");
  if (/(?:ой)$/.test(male)) return male.replace(/ой$/, "ая");
  if (INVARIANT.test(male)) return male;
  if (/(?:ов|ёв|ев|ин|ын)$/.test(male)) return male + "а";
  return male;
}

export interface PersonName {
  gender: Gender;
  first: string;
  middle: string;
  last: string;
  /** «Фамилия Имя Отчество» */
  full: string;
  /** «Фамилия И.О.» */
  short: string;
}

export function makeName(gender: Gender, first: string, middle: string, lastMale: string): PersonName {
  const last = gender === "F" ? feminineSurname(lastMale) : lastMale;
  return {
    gender,
    first,
    middle,
    last,
    full: `${last} ${first} ${middle}`,
    short: `${last} ${first[0]}.${middle[0]}.`,
  };
}

export function randomName(rng: Rng, gender: Gender = rng.chance(0.5) ? "M" : "F"): PersonName {
  const first = gender === "M" ? rng.pick(MALE_NAMES) : rng.pick(FEMALE_NAMES);
  const [m, f] = rng.pick(PATRONYMICS);
  return makeName(gender, first, gender === "M" ? m : f, rng.pick(SURNAMES));
}

/** Буквы, допустимые в российских госномерах (совпадают по начертанию с латиницей) */
export const PLATE_LETTERS = ["А", "В", "Е", "К", "М", "Н", "О", "Р", "С", "Т", "У", "Х"] as const;

/** Госномер формата А123ВС 47 (регион задаётся — у вымышленного города свой код) */
export function randomPlate(rng: Rng, region: string): string {
  const l = () => rng.pick(PLATE_LETTERS);
  const digits = String(rng.int(1, 999)).padStart(3, "0");
  return `${l()}${digits}${l()}${l()} ${region}`;
}

/** Мобильный номер в формате +7 9XX XXX-XX-XX */
export function randomPhone(rng: Rng): string {
  const code = rng.int(900, 999);
  const a = String(rng.int(0, 999)).padStart(3, "0");
  const b = String(rng.int(0, 99)).padStart(2, "0");
  const c = String(rng.int(0, 99)).padStart(2, "0");
  return `+7 ${code} ${a}-${b}-${c}`;
}

/** Маскированный номер банковской карты: 2202 **** **** 1234 */
export function randomCardMask(rng: Rng): string {
  const prefix = rng.pick(["2200", "2202", "2204", "4276", "5536"]);
  return `${prefix} **** **** ${String(rng.int(0, 9999)).padStart(4, "0")}`;
}

/**
 * Уникальные значения: повторяет генератор, пока не получит новое.
 * reserved — ключи заложенных фактов, которые шум не должен повторить
 * (например, номер машины убийцы не может случайно достаться прохожему).
 */
export function uniqueFactory<T>(
  make: () => T,
  key: (v: T) => string = String,
  reserved: Iterable<string> = []
): () => T {
  const seen = new Set<string>(reserved);
  return () => {
    for (let i = 0; i < 10_000; i++) {
      const v = make();
      const k = key(v);
      if (!seen.has(k)) {
        seen.add(k);
        return v;
      }
    }
    throw new Error("uniqueFactory: пул исчерпан");
  };
}

