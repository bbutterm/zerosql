const TRANSLIT: Readonly<Record<string, string>> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y",
  к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
  х: "kh", ц: "ts", ч: "ch", ш: "sh", щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/** Транслитерация для логинов: «Вальц» → «valts», «Шустова» → «shustova» */
export function translit(text: string): string {
  let out = "";
  for (const ch of text.toLowerCase()) out += TRANSLIT[ch] ?? (/[a-z0-9]/.test(ch) ? ch : "");
  return out;
}

/** Логин сотрудника: первая буква имени + «.» + фамилия латиницей ('i.valts') */
export function loginFor(first: string, last: string): string {
  return `${translit(first)[0] ?? "x"}.${translit(last)}`;
}

/**
 * Все телефоны мира — в вымышленном диапазоне +7 900 000-XX-XX
 * (разд. 8.2 библии): так ни один номер не совпадёт с настоящим.
 */
export function fictionalPhone(rng: Rng): string {
  return phoneFromDigits(rng.int(0, 9999));
}

/** 1219 → '+7 900 000-12-19' */
export function phoneFromDigits(n: number): string {
  const s = String(n).padStart(4, "0");
  return `+7 900 000-${s.slice(0, 2)}-${s.slice(2)}`;
}

/** Госномер без региона, как в реестре мира: 'К404ТО' */
export function plateNoRegion(rng: Rng): string {
  const l = () => rng.pick(PLATE_LETTERS);
  return `${l()}${String(rng.int(1, 999)).padStart(3, "0")}${l()}${l()}`;
}

/** Кириллица → латинский двойник (ошибки OCR и ручного ввода) */
export const HOMOGLYPHS: Readonly<Record<string, string>> = {
  А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", У: "Y", Х: "X",
};

/** Заменяет в номере часть кириллических букв на латинские двойники */
export function homoglyphPlate(rng: Rng, plate: string, all = false): string {
  const chars = [...plate];
  const letters = chars.map((c, i) => (HOMOGLYPHS[c] ? i : -1)).filter((i) => i >= 0);
  if (letters.length === 0) return plate;
  const swap = all ? letters : rng.sample(letters, rng.int(1, Math.min(2, letters.length)));
  for (const i of swap) chars[i] = HOMOGLYPHS[chars[i]];
  return chars.join("");
}

/** «Фамилия И. О.» с пробелами, как в staff.full_name и key_owner: 'Лыков А. С.' */
export function shortName(last: string, first: string, middle: string | null): string {
  return middle ? `${last} ${first[0]}. ${middle[0]}.` : `${last} ${first[0]}.`;
}
